CREATE DATABASE PIZZARIA;
CREATE TABLE CLIENTE 
(
	CPF_CLIENTE VARCHAR(50) PRIMARY KEY NOT NULL,
	NOME VARCHAR(70) NOT NULL,
	RUA VARCHAR(50) NOT NULL,
	NUMERO INT NOT NULL,
	BAIRRO VARCHAR (35) NOT NULL
)
CREATE TABLE ENTREGADOR
(
	MATRICULA_ENTREGADOR VARCHAR(50) PRIMARY KEY NOT NULL,
	NOME VARCHAR(70) NOT NULL,
	PLACA_MOTO VARCHAR (8) NOT NULL,
)




CREATE TABLE PEDIDO
(
	NUMERO_PEDIDO INT PRIMARY KEY NOT NULL,
	CPF_CLIENTE VARCHAR(50) NOT NULL,
	MATRICULA_ENTREGADOR VARCHAR(50) NOT NULL,
	DATA_PEDIDO DATE NOT NULL,
	HORA_PEDIDO TIME  NOT NULL
	CONSTRAINT FK_CPF_CLIENTE FOREIGN KEY (CPF_CLIENTE) 
	REFERENCES CLIENTE(CPF_CLIENTE),
	CONSTRAINT FK_MATRICULA_ENTREGADOR FOREIGN KEY (MATRICULA_ENTREGADOR) 
	REFERENCES ENTREGADOR(MATRICULA_ENTREGADOR)
	
)
CREATE TABLE PIZZA 
(
	CODIGO_PIZZA INT PRIMARY KEY NOT NULL,
	NOME VARCHAR(70) NOT NULL,
	PRECO DECIMAL(10,2) NOT NULL
)
CREATE TABLE ITEM_PEDIDO
(
	ID_PEDIDO INT PRIMARY KEY NOT NULL,
	NUMERO_PEDIDO INT NOT NULL,
	CODIGO_PIZZA INT NOT NULL,
	QUANTIDADE INT NOT NULL
	CONSTRAINT FK_NUMERO_PEDIDO FOREIGN KEY (NUMERO_PEDIDO) 
	REFERENCES PEDIDO(NUMERO_PEDIDO),
	CONSTRAINT FK_CODIGO_PIZZA FOREIGN KEY (CODIGO_PIZZA) 
	REFERENCES PIZZA(CODIGO_PIZZA),
)
CREATE TABLE TELEFONE
(
	ID_TELEFONE VARCHAR(50) PRIMARY KEY NOT NULL,
	CPF_CLIENTE VARCHAR (50),
	NUMERO VARCHAR(50)
	CONSTRAINT FK_CPF_CLIENTE FOREIGN KEY (CPF_CLIENTE) 
	REFERENCES CLIENTE(CPF_CLIENTE)
)

